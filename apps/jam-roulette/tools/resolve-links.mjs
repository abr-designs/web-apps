const REQUEST_DELAY_MS = 300;
const RETRY_DELAY_MS = 5000;
const HEADERS = { "User-Agent": "jam-roulette-link-resolver (abr-designs/web-apps)" };

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

/** @created Claude (claude-opus-5-5) 2026-10-13 */
function normalize(title) {
  return title.toLowerCase().normalize("NFD").replace(/\p{M}/gu, "")
    .replace(/[™®©]/g, "").replace(/[^a-z0-9]+/g, " ").trim();
}

/** @created Claude (claude-opus-5-5) 2026-10-13 */
async function steamUrl(game, retries = 2) {
  // Reference names may carry a year to tell versions apart, e.g. "Prey (2017)"; Steam titles don't.
  const title = game.replace(/\s*\(\d{4}\)$/, "");
  const res = await fetch(`https://store.steampowered.com/api/storesearch/?term=${encodeURIComponent(title)}&l=english&cc=US`, { headers: HEADERS });
  if (res.status === 429 && retries > 0) {
    await sleep(RETRY_DELAY_MS);
    return steamUrl(game, retries - 1);
  }
  if (!res.ok) return null;
  const { items = [] } = await res.json();
  const hit = items.find((item) => normalize(item.name) === normalize(title));
  return hit ? `${STEAM}${hit.id}/` : null;
}

const games = [...new Set(REELS.filter((r) => !r.visual).flatMap((r) => r.entries.flatMap(([, ...refs]) => refs)))].sort();

const links = {};
const missing = [];
for (const game of games) {
  let url = OVERRIDES[game];
  if (!url) {
    url = await steamUrl(game);
    await sleep(REQUEST_DELAY_MS);
  }
  if (url) {
    links[game] = url;
    console.log(`${game} -> ${url}`);
  } else {
    missing.push(game);
  }
}

if (missing.length) {
  console.error(`MISSING ${missing.length}, js/links.js left unchanged: ${missing.join(", ")}`);
  process.exit(1);
}

const body = Object.entries(links).map(([game, url]) => `  ${JSON.stringify(game)}: ${JSON.stringify(url)},`).join("\n");
await writeFile(
  new URL("../js/links.js", import.meta.url),
  `// Generated by tools/resolve-links.mjs. Do not edit by hand; pin fixes in OVERRIDES there.\n\nexport const LINKS = {\n${body}\n};\n`,
);
console.log(`wrote ${games.length} links`);
